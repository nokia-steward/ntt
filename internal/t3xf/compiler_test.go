func TestMessagePortCompiler(t *testing.T) {
	tests := []struct {
		name string
		src  string
		want []opcode.Opcode
	}{
		{
			name: "port type",
			src: `module M {
type port P message {
  address integer;
  inout integer;
  map param (integer x);
  unmap param (integer x);
}
}`,
			want: []opcode.Opcode{opcode.PORTMA},
		},
		{
			name: "later global address",
			src: `module M {
type port P message { inout integer }
type integer address;
}`,
			want: []opcode.Opcode{opcode.PORTMA},
		},
		{
			name: "send and configuration",
			src: `module M {
type port P message { inout integer }
type component C { port P p }
testcase tc() runs on C system C {
  var C c := C.create;
  connect(self:p, c:p);
  p.send(1);
  p.send(2) to c;
  p.send(3) to (c, mtc);
  p.send(4) to all component;
  disconnect(self:p, c:p);
  disconnect;
  map(self:p, system:p);
  unmap(self:p, system:p);
  unmap;
}
}`,
			want: []opcode.Opcode{
				opcode.CONNECT,
				opcode.SEND, opcode.SEND1, opcode.SENDN, opcode.SENDA,
				opcode.DISCONNECT, opcode.DISCONNECTA,
				opcode.MAP, opcode.UNMAP, opcode.UNMAPA,
			},
		},
		{
			name: "receive and lifecycle",
			src: `module M {
type port P message { inout integer }
type component C { port P p }
testcase tc() runs on C {
  alt {
    [] p.receive(integer:?) {}
    [] p.trigger {}
    [] p.check(receive(integer:?)) {}
    [] any port.receive {}
  }
  p.clear;
  p.halt;
  all port.start;
  all port.stop;
  log(p.checkstate("Started"));
}
}`,
			want: []opcode.Opcode{
				opcode.RECEIVE, opcode.TRIGGER, opcode.RECEIVEC, opcode.RECEIVE1,
				opcode.CLEAR, opcode.HALT, opcode.STARTAP, opcode.STOPAP, opcode.CHECKSTATE,
			},
		},
		{
			name: "standalone nodefault receive",
			src: `module M {
type port P message { inout integer }
type component C { port P p }
testcase tc() runs on C { @nodefault p.receive }
}`,
			want: []opcode.Opcode{opcode.RECEIVE, opcode.ALTND},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			root := syntax.Parse([]byte(tt.src))
			assert.NoError(t, root.Err())
			c := t3xf.NewCompiler()
			assert.NoError(t, c.Compile(root))
			code, err := c.Assemble()
			assert.NoError(t, err)
			instructions, err := t3xf.Disassemble(code)
			assert.NoError(t, err)
			var got []opcode.Opcode
			for _, instruction := range instructions {
				if slices.Contains(tt.want, instruction.Op) {
					got = append(got, instruction.Op)
				}
			}
			assert.Equal(t, tt.want, got)
		})
	}
}
