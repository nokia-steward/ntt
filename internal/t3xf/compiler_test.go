func TestUnsupportedLiteral(t *testing.T) {
	for _, input := range []string{"not_a_number", "'2'B", "'A'O"} {
		root := syntax.Parse([]byte(input))
		root.Filename = "test.ttcn3"
		if root.Err() != nil {
			t.Fatalf("syntax.Parse(%q) returned error: %v", input, root.Err())
		}
		c := t3xf.NewCompiler()
		err := c.Compile(root)
		if assert.Error(t, err, input) {
			assert.Contains(t, err.Error(), "test.ttcn3:")
		}
		if _, err := c.Assemble(); err == nil {
			t.Errorf("%s: expected an error", input)
		}
	}

	root := syntax.Parse([]byte("module M { control { log(undef) } }"))
	root.Filename = "undef.ttcn3"
	c := t3xf.NewCompiler()
	assert.NoError(t, c.Compile(root))
	_, err := c.Assemble()
	if assert.Error(t, err) {
		assert.Contains(t, err.Error(), `undef.ttcn3:1:26-1:31: "undef" undefined`)
	}
}

func TestCompileImage(t *testing.T) {
	file := filepath.Join(t.TempDir(), "example.ttcn3")
	src := []byte("module example { control { log(1) } }\n")
	if err := os.WriteFile(file, src, 0o644); err != nil {
		t.Fatal(err)
	}
	b, err := t3xf.CompileImage(file)
	assert.NoError(t, err)
	assert.NotEmpty(t, b)
}

func TestNodefaultParser(t *testing.T) {
	root := syntax.Parse([]byte(`module M {
type port P message { in integer }
type component C { port P p }
function f() runs on C { @nodefault p.receive }
}`))
	assert.NoError(t, root.Err())
	found := false
	root.Inspect(func(n syntax.Node) bool {
		if stmt, ok := n.(*syntax.ExprStmt); ok && stmt.NoDefault != nil {
			found = true
		}
		return true
	})
	assert.True(t, found)
}

func TestPortAddressParser(t *testing.T) {
	root := syntax.Parse([]byte(`module M {
type record A { integer host }
type port P message { address A; inout charstring }
type component C { port P p }
testcase tc() runs on C {
  var P.address a := { host := 1 };
  log(a.host);
  setverdict(pass);
}
control { execute(tc()) }
}`))
	assert.NoError(t, root.Err())
	c := t3xf.NewImageCompiler()
	assert.NoError(t, c.Compile(root))
	_, err := c.Assemble()
	assert.NoError(t, err)
}

