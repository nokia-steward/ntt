// gen consumes nodes.yaml and emits nodes_gen.go.
//
// The flow is deliberately small: a single YAML file defines every
// AST node, and this Go program turns it into structs, kinds,
// children accessors and a visitor interface.
// Adding a new node type becomes a documentation-driven activity rather
// than a copy/paste exercise across nodes.go, nodes_gen.go and every
// switch statement in the LSP.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strings"
	"text/template"

	"gopkg.in/yaml.v3"
)

type field struct {
	Name string
	Type string
}

type node struct {
	Name string `yaml:"name"`
	Doc  string `yaml:"doc"`
	// FieldsRaw is the on-disk shape of fields: an ordered map of
	// name -> type. We post-process it into Fields after unmarshal so
	// the template sees a stable slice.
	FieldsRaw yaml.Node `yaml:"fields"`

	// Fields is the decoded form. It is not populated by the YAML
	// decoder.
	Fields []field `yaml:"-"`
}

type schema struct {
	Nodes []node `yaml:"nodes"`
}

const tmplSrc = `// Code generated by gen/main.go. DO NOT EDIT.

package nodes

// NodeKind enumerates every node type defined in nodes.yaml.
type NodeKind int

const (
{{- range $i, $n := .Nodes }}
	Kind{{ $n.Name }} NodeKind = {{ $i }}
{{- end }}
)

// String returns the human-readable name of a NodeKind.
func (k NodeKind) String() string {
	switch k {
{{- range .Nodes }}
	case Kind{{ .Name }}:
		return "{{ .Name }}"
{{- end }}
	}
	return "<unknown>"
}

// Token is the minimal interface a generated node field needs from its
// scanner-level token type. Keeping it as an interface lets the
// generated code stay independent from the rest of the syntax package.
type Token interface{}

// Node is implemented by every generated node type.
type Node interface {
	Kind() NodeKind
	Children() []Node
	Accept(Visitor)
}

// Visitor uses a dedicated Visit<Name> method per node so consumers can
// dispatch without writing switch statements.
type Visitor interface {
{{- range .Nodes }}
	Visit{{ .Name }}(*{{ .Name }})
{{- end }}
}

{{- range .Nodes }}

{{ comment .Doc }}
type {{ .Name }} struct {
{{- range .Fields }}
	{{ .Name }} {{ fieldType .Type }}
{{- end }}
}

// Kind returns Kind{{ .Name }}.
func (n *{{ .Name }}) Kind() NodeKind { return Kind{{ .Name }} }

// Accept dispatches v.Visit{{ .Name }}(n).
func (n *{{ .Name }}) Accept(v Visitor) { v.Visit{{ .Name }}(n) }

// Children returns the node-typed fields of n in source order.
func (n *{{ .Name }}) Children() []Node {
	var out []Node
{{- range .Fields }}
{{- if isNodePtr .Type }}
	if n.{{ .Name }} != nil {
		out = append(out, n.{{ .Name }})
	}
{{- else if isNodeSlice .Type }}
	for _, c := range n.{{ .Name }} {
		if c != nil {
			out = append(out, c)
		}
	}
{{- end }}
{{- end }}
	return out
}
{{- end }}
`

func main() {
	in, err := os.ReadFile("nodes.yaml")
	if err != nil {
		log.Fatal(err)
	}
	var s schema
	if err := yaml.Unmarshal(in, &s); err != nil {
		log.Fatal(err)
	}
	if len(s.Nodes) == 0 {
		log.Fatal("no nodes defined")
	}
	for i := range s.Nodes {
		fs, err := decodeFields(s.Nodes[i].FieldsRaw)
		if err != nil {
			log.Fatalf("node %s: %v", s.Nodes[i].Name, err)
		}
		s.Nodes[i].Fields = fs
	}
	sort.SliceStable(s.Nodes, func(i, j int) bool {
		return s.Nodes[i].Name < s.Nodes[j].Name
	})

	funcs := template.FuncMap{
		"comment":     comment,
		"fieldType":   fieldType,
		"isNodePtr":   isNodePtr,
		"isNodeSlice": isNodeSlice,
	}
	t, err := template.New("nodes").Funcs(funcs).Parse(tmplSrc)
	if err != nil {
		log.Fatal(err)
	}
	var buf bytes.Buffer
	if err := t.Execute(&buf, s); err != nil {
		log.Fatal(err)
	}
	out, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, buf.String())
		log.Fatal(err)
	}
	if err := os.WriteFile("nodes_gen.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}

// decodeFields turns a YAML mapping node into a slice of fields,
// preserving the original document order. yaml.v3's MappingNode lays
// content out as alternating [key, value, key, value, ...] pairs, so we
// just walk that.
func decodeFields(n yaml.Node) ([]field, error) {
	if n.Kind == 0 {
		return nil, nil
	}
	if n.Kind != yaml.MappingNode {
		return nil, fmt.Errorf("expected mapping, got kind %d", n.Kind)
	}
	if len(n.Content)%2 != 0 {
		return nil, fmt.Errorf("malformed mapping: odd content length")
	}
	out := make([]field, 0, len(n.Content)/2)
	for i := 0; i < len(n.Content); i += 2 {
		k := n.Content[i]
		v := n.Content[i+1]
		out = append(out, field{Name: k.Value, Type: v.Value})
	}
	return out, nil
}

func comment(s string) string {
	lines := strings.Split(strings.TrimSpace(s), "\n")
	var out []string
	for _, l := range lines {
		out = append(out, "// "+l)
	}
	return strings.Join(out, "\n")
}

func fieldType(t string) string {
	switch {
	case t == "token":
		return "Token"
	case t == "[]token":
		return "[]Token"
	case strings.HasPrefix(t, "*"):
		return "*" + strings.TrimPrefix(t, "*")
	case strings.HasPrefix(t, "[]"):
		return "[]*" + strings.TrimPrefix(t, "[]")
	}
	return t
}

func isNodePtr(t string) bool { return strings.HasPrefix(t, "*") }

func isNodeSlice(t string) bool { return strings.HasPrefix(t, "[]") && t != "[]token" }
