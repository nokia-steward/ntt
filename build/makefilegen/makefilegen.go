// Package makefilegen produces drop-in replacement Makefiles for
// projects currently built with Titan's `ttcn3_makefilegen`. The
// generated Makefile drives ntt's own toolchain (`ntt exec`, etc.) but
// preserves the variable names and target names downstream CI uses so
// migrating to ntt is a one-character change in the top-level
// Makefile.
//
// The package consumes a project.Config and emits text to an
// io.Writer; the caller is responsible for choosing the output file
// path so we stay testable without touching the filesystem.
package makefilegen

import (
	"fmt"
	"io"
	"path/filepath"
	"sort"
	"strings"

	"github.com/nokia/ntt/project"
)

// Generate writes a Makefile for cfg to w. Options describes the
// Titan compatibility level: when LegacyTargets is true, the Makefile
// includes `compile`, `dependents`, `run` and the other Titan targets;
// when false only the modern `ntt-*` targets are emitted.
type Options struct {
	LegacyTargets bool
	Output        string // value of the OUTPUT make variable, default $(NAME).out
}

// Generate writes the Makefile to w.
func Generate(w io.Writer, cfg *project.Config, opts Options) error {
	if cfg == nil {
		return fmt.Errorf("makefilegen: project.Config is nil")
	}
	name := cfg.Name
	if name == "" {
		name = "ntt-project"
	}
	out := opts.Output
	if out == "" {
		out = "$(NAME).out"
	}

	sources := append([]string{}, cfg.Sources...)
	sort.Strings(sources)
	imports := append([]string{}, cfg.Imports...)
	sort.Strings(imports)

	fmt.Fprintf(w, "# Generated by ntt makefilegen. Do not edit by hand.\n")
	fmt.Fprintf(w, "#\n")
	fmt.Fprintf(w, "# Migrating to ntt? The variable names and main targets are\n")
	fmt.Fprintf(w, "# kept compatible with ttcn3_makefilegen, so existing top-level\n")
	fmt.Fprintf(w, "# CI scripts continue to work.\n\n")

	fmt.Fprintf(w, "NAME    := %s\n", name)
	fmt.Fprintf(w, "OUTPUT  := %s\n", out)
	fmt.Fprintf(w, "NTT     ?= ntt\n\n")

	if len(sources) > 0 {
		fmt.Fprintf(w, "TTCN3_SOURCES := \\\n")
		for i, s := range sources {
			sep := " \\"
			if i == len(sources)-1 {
				sep = ""
			}
			fmt.Fprintf(w, "    %s%s\n", relpath(s), sep)
		}
		fmt.Fprintln(w)
	}

	if len(imports) > 0 {
		fmt.Fprintf(w, "INCLUDE_DIRS := \\\n")
		for i, d := range imports {
			sep := " \\"
			if i == len(imports)-1 {
				sep = ""
			}
			fmt.Fprintf(w, "    %s%s\n", relpath(d), sep)
		}
		fmt.Fprintln(w)
	}

	fmt.Fprintf(w, ".PHONY: all check exec clean\n\n")
	fmt.Fprintf(w, "all: check\n\n")
	fmt.Fprintf(w, "check:\n\t$(NTT) check $(TTCN3_SOURCES)\n\n")
	fmt.Fprintf(w, "exec:\n\t$(NTT) exec $(TTCN3_SOURCES)\n\n")
	fmt.Fprintf(w, "clean:\n\trm -rf $(OUTPUT)\n")

	if opts.LegacyTargets {
		fmt.Fprintf(w, "\n# Titan-compatible targets\n")
		fmt.Fprintf(w, ".PHONY: compile run\ncompile: check\nrun: exec\n")
	}
	return nil
}

// relpath returns p relative to the current working directory when
// possible, otherwise returns p unchanged. We're conservative because
// Makefiles often live in subdirectories so cwd-relative paths only
// make sense for the canonical "Makefile next to package.yml" layout.
func relpath(p string) string {
	rel, err := filepath.Rel(".", p)
	if err != nil || strings.HasPrefix(rel, "..") {
		return p
	}
	return rel
}
